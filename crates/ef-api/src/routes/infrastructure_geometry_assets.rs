//! Tenant-scoped geometry asset ingress and delivery.
//! The first provider is local filesystem storage. Only self-contained GLB v2
//! packages are accepted; arbitrary URLs and external glTF dependencies are never fetched.
use axum::{
    body::{Body, to_bytes},
    extract::State,
    http::{HeaderMap, HeaderValue, StatusCode, header},
    response::{IntoResponse, Response},
    Json,
};
use serde_json::{Value, json};
use sha2::{Digest, Sha256};
use sqlx::FromRow;
use std::path::PathBuf;
use uuid::Uuid;

use crate::middleware::auth_extractor::{AppState, AuthContext};
use crate::middleware::error_response::ApiError;

type ApiResult<T> = Result<T, (StatusCode, Json<ApiError>)>;
const MAX_ASSET_BYTES: usize = 100 * 1024 * 1024;
const GLB_MEDIA_TYPE: &str = "model/gltf-binary";

#[derive(Debug, FromRow)]
struct GeometryAssetRow {
    id: Uuid,
    sha256: String,
    format: String,
    media_type: String,
    size_bytes: i64,
    storage_key: String,
}

/// Provider boundary: storage keys are generated by EdgeFabric and never
/// derived from user filenames or paths. An S3-compatible implementation can
/// implement this same contract later without changing asset identity/API.
struct LocalFilesystemProvider {
    root: PathBuf,
}

impl LocalFilesystemProvider {
    fn new() -> Result<Self, std::io::Error> {
        let root = std::env::var_os("EF_GEOMETRY_STORAGE_ROOT")
            .map(PathBuf::from)
            .unwrap_or_else(|| PathBuf::from("./var/geometry-assets"));
        std::fs::create_dir_all(&root)?;
        let root = std::fs::canonicalize(root)?;
        Ok(Self { root })
    }

    fn path_for(&self, key: &str) -> Result<PathBuf, std::io::Error> {
        // UUID-only keys prevent traversal and keep filenames independent of
        // client-controlled names. Reject anything outside this narrow form.
        let id = Uuid::parse_str(key).map_err(|_| std::io::Error::new(
            std::io::ErrorKind::InvalidInput, "invalid storage key"
        ))?;
        Ok(self.root.join(id.to_string()))
    }

    async fn put(&self, id: Uuid, bytes: &[u8]) -> Result<(), std::io::Error> {
        use tokio::io::AsyncWriteExt;
        let path = self.path_for(&id.to_string())?;
        let mut file = tokio::fs::OpenOptions::new()
            .write(true).create_new(true).open(path).await?;
        if let Err(error) = file.write_all(bytes).await {
            drop(file);
            let _ = tokio::fs::remove_file(self.path_for(&id.to_string())?).await;
            return Err(error);
        }
        file.sync_all().await
    }

    async fn read(&self, key: &str) -> Result<Vec<u8>, std::io::Error> {
        tokio::fs::read(self.path_for(key)?).await
    }

    async fn delete(&self, key: &str) {
        if let Ok(path) = self.path_for(key) { let _ = tokio::fs::remove_file(path).await; }
    }
}

fn sha256_hex(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

fn validate_glb(bytes: &[u8]) -> Result<(), &'static str> {
    if bytes.len() < 20 { return Err("GLB file is truncated"); }
    if &bytes[0..4] != b"glTF" { return Err("Geometry asset must be a binary glTF (GLB) file"); }
    let version = u32::from_le_bytes(bytes[4..8].try_into().unwrap_or([0; 4]));
    let declared_length = u32::from_le_bytes(bytes[8..12].try_into().unwrap_or([0; 4])) as usize;
    if version != 2 { return Err("Only GLB version 2 is supported"); }
    if declared_length != bytes.len() { return Err("GLB declared length does not match uploaded bytes"); }
    let first_chunk_length = u32::from_le_bytes(bytes[12..16].try_into().unwrap_or([0; 4])) as usize;
    let first_chunk_type = u32::from_le_bytes(bytes[16..20].try_into().unwrap_or([0; 4]));
    // JSON is the mandatory first GLB chunk. Its content is parsed to reject
    // external buffers/images; GLB-contained binary chunks remain self-contained.
    if first_chunk_type != 0x4E4F534A || first_chunk_length > bytes.len().saturating_sub(20) {
        return Err("GLB must begin with a valid JSON chunk");
    }
    let json_bytes = &bytes[20..20 + first_chunk_length];
    let document: Value = serde_json::from_slice(json_bytes).map_err(|_| "GLB JSON chunk is invalid")?;
    if document["buffers"].as_array().is_some_and(|items| items.iter().any(|item| item.get("uri").is_some()))
        || document["images"].as_array().is_some_and(|items| items.iter().any(|item| item.get("uri").is_some()))
    {
        return Err("External GLB buffer or image URIs are not supported");
    }
    Ok(())
}

/// POST /api/v1/infrastructure/geometry-assets
/// Raw request body; required headers: Content-Type, X-Asset-License.
/// Optional X-Asset-Units. Content digest is computed server-side.
pub async fn upload(
    State(state): State<AppState>,
    auth: AuthContext,
    headers: HeaderMap,
    body: Body,
) -> ApiResult<Json<Value>> {
    let media_type = headers.get(header::CONTENT_TYPE)
        .and_then(|v| v.to_str().ok()).unwrap_or("").split(';').next().unwrap_or("").trim();
    if media_type != GLB_MEDIA_TYPE {
        return Err(ApiError::bad_request("Content-Type must be model/gltf-binary; only GLB is accepted"));
    }
    let license = headers.get("x-asset-license")
        .and_then(|v| v.to_str().ok()).map(str::trim).filter(|v| !v.is_empty() && v.len() <= 500)
        .ok_or_else(|| ApiError::bad_request("X-Asset-License is required (maximum 500 characters)"))?;
    let units = headers.get("x-asset-units").and_then(|v| v.to_str().ok())
        .map(str::trim).filter(|v| !v.is_empty() && v.len() <= 64).map(str::to_owned);
    let bytes = to_bytes(body, MAX_ASSET_BYTES).await
        .map_err(|_| ApiError::bad_request("Geometry asset exceeds the 100 MiB upload limit"))?;
    validate_glb(&bytes).map_err(ApiError::bad_request)?;
    let digest = sha256_hex(&bytes);
    let id = Uuid::new_v4();
    let provider = LocalFilesystemProvider::new()
        .map_err(|error| { tracing::error!(error = %error, "Geometry storage initialization failed"); ApiError::internal("Geometry storage unavailable") })?;
    provider.put(id, &bytes).await
        .map_err(|error| { tracing::error!(error = %error, "Geometry asset write failed"); ApiError::internal("Failed to store geometry asset") })?;

    let result = sqlx::query(
        r#"INSERT INTO infrastructure_geometry_assets
           (id, tenant_id, sha256, format, media_type, size_bytes, license, units, storage_key)
           VALUES ($1,$2,$3,'glb',$4,$5,$6,$7,$8)"#
    )
    .bind(id).bind(auth.tenant_id).bind(&digest).bind(GLB_MEDIA_TYPE)
    .bind(bytes.len() as i64).bind(license).bind(&units).bind(id.to_string())
    .execute(&state.pool).await;
    if let Err(error) = result {
        provider.delete(&id.to_string()).await;
        tracing::error!(tenant_id = %auth.tenant_id, error = %error, "Geometry asset metadata insert failed");
        return Err(ApiError::internal("Failed to register geometry asset"));
    }

    Ok(Json(json!({
        "asset": {
            "id": id,
            "uri": format!("artifact://geometry/{id}"),
            "format": "glb",
            "media_type": GLB_MEDIA_TYPE,
            "sha256": digest,
            "size_bytes": bytes.len(),
            "license": license,
            "units": units,
            "download_path": format!("/api/v1/infrastructure/geometry-assets/{id}/content")
        },
        "storage_provider": "local_filesystem",
        "tenant_scoped": true
    })))
}

/// GET /api/v1/infrastructure/geometry-assets/:id/content
pub async fn download(
    State(state): State<AppState>,
    auth: AuthContext,
    axum::extract::Path(id): axum::extract::Path<Uuid>,
) -> ApiResult<Response> {
    let row = sqlx::query_as::<_, GeometryAssetRow>(
        r#"SELECT id, sha256, format, media_type, size_bytes, storage_key
           FROM infrastructure_geometry_assets WHERE id = $1 AND tenant_id = $2"#
    ).bind(id).bind(auth.tenant_id).fetch_optional(&state.pool).await
        .map_err(|error| { tracing::error!(error = %error, "Geometry asset lookup failed"); ApiError::internal("Failed to load geometry asset") })?
        .ok_or_else(|| ApiError::not_found("Geometry asset not found"))?;

    if row.format != "glb" || row.media_type != GLB_MEDIA_TYPE || row.size_bytes <= 0 || row.size_bytes as usize > MAX_ASSET_BYTES {
        return Err(ApiError::bad_request("Stored geometry asset metadata is unsupported"));
    }
    let provider = LocalFilesystemProvider::new()
        .map_err(|_| ApiError::internal("Geometry storage unavailable"))?;
    let bytes = provider.read(&row.storage_key).await
        .map_err(|_| ApiError::not_found("Geometry asset content not found"))?;
    if bytes.len() != row.size_bytes as usize || sha256_hex(&bytes) != row.sha256 {
        tracing::error!(asset_id = %row.id, tenant_id = %row.tenant_id, "Geometry asset integrity verification failed");
        return Err(ApiError::internal("Geometry asset integrity check failed"));
    }
    validate_glb(&bytes).map_err(ApiError::bad_request)?;
    let mut response = Response::new(Body::from(bytes));
    *response.status_mut() = StatusCode::OK;
    response.headers_mut().insert(header::CONTENT_TYPE, HeaderValue::from_static(GLB_MEDIA_TYPE));
    response.headers_mut().insert(header::CACHE_CONTROL, HeaderValue::from_static("private, no-store"));
    response.headers_mut().insert(axum::http::HeaderName::from_static("x-content-type-options"), HeaderValue::from_static("nosniff"));
    response.headers_mut().insert(header::CONTENT_LENGTH, HeaderValue::from_str(&row.size_bytes.to_string()).unwrap_or(HeaderValue::from_static("0")));
    Ok(response)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn glb_with_json(json: &str) -> Vec<u8> {
        let mut chunk = json.as_bytes().to_vec();
        while chunk.len() % 4 != 0 { chunk.push(b' '); }
        let mut bytes = Vec::new();
        bytes.extend_from_slice(b"glTF");
        bytes.extend_from_slice(&2_u32.to_le_bytes());
        bytes.extend_from_slice(&((20 + chunk.len()) as u32).to_le_bytes());
        bytes.extend_from_slice(&(chunk.len() as u32).to_le_bytes());
        bytes.extend_from_slice(&0x4E4F534A_u32.to_le_bytes());
        bytes.extend_from_slice(&chunk);
        bytes
    }

    #[test]
    fn accepts_self_contained_glb_v2() {
        let bytes = glb_with_json(r#"{"asset":{"version":"2.0"},"scene":0,"scenes":[{}]}"#);
        assert!(validate_glb(&bytes).is_ok());
    }

    #[test]
    fn rejects_external_glb_dependencies() {
        let bytes = glb_with_json(r#"{"asset":{"version":"2.0"},"buffers":[{"uri":"https://example.invalid/model.bin"}]}"#);
        assert_eq!(validate_glb(&bytes), Err("External GLB buffer or image URIs are not supported"));
    }

    #[test]
    fn rejects_mismatched_declared_length_and_non_glb() {
        assert!(validate_glb(b"not a glb file").is_err());
        let mut bytes = glb_with_json(r#"{"asset":{"version":"2.0"}}"#);
        bytes[8..12].copy_from_slice(&1_u32.to_le_bytes());
        assert_eq!(validate_glb(&bytes), Err("GLB declared length does not match uploaded bytes"));
    }

    #[test]
    fn storage_keys_must_be_uuids() {
        assert!(Uuid::parse_str("../outside").is_err());
        assert!(Uuid::parse_str(&Uuid::new_v4().to_string()).is_ok());
    }
}
